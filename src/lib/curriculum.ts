/**
 * منهج الطباعة العربية باللمس — 30 مرحلة (6 مراحل × 5 مستويات).
 * مبني على لوحة المفاتيح العربية (101) بمنهجية الصف الرئيسي أولاً
 * (أصابع السبابة على «ت» و «ن» — مفاتيح الارتكاز).
 * التدرج: مؤقت الحرف 6ث ← 2.5ث، مؤقت السطر 90ث ← 40ث، القلوب 4 ← 3 ← 2.
 */

export interface LevelRulesOverride {
  hearts?: number
  letterSeconds?: number
  lineSeconds?: number
  enemySpeed?: number // 1..10
}

export interface LevelDef {
  id: number
  stage: number
  name: string
  isReview: boolean
  lines: string[]
  targetWpm: number
  rules: LevelRulesOverride
}

export interface StageDef {
  id: number
  name: string
  levels: LevelDef[]
}

const lerp = (a: number, b: number, t: number) => a + (b - a) * t

/** قواعد متدرجة حسب رقم المرحلة (1..30) */
function scaleRules(id: number): LevelRulesOverride {
  const t = (id - 1) / 29
  return {
    hearts: id <= 12 ? 4 : id <= 24 ? 3 : 2,
    letterSeconds: Math.round(lerp(6, 2.5, t) * 10) / 10,
    lineSeconds: Math.round(lerp(90, 40, t)),
    enemySpeed: Math.min(10, Math.max(1, Math.round(lerp(1, 10, t)))),
  }
}

function level(id: number, stage: number, name: string, lines: string[], targetWpm: number, isReview = false): LevelDef {
  return { id, stage, name, isReview, lines, targetWpm, rules: scaleRules(id) }
}

